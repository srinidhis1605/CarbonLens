// backend/routes/v2Agent.js
const express = require('express');
const router = express.Router();
const authenticateToken = require('../middleware/authMiddleware');
const { runSustainabilityAgent } = require('../services/sustainabilityAgentService');
const {
    getRawAnalysisRow,
    saveAgentReport,
    getAgentReportsByUser,
    getLatestAgentReportForAnalysis,
} = require('../services/v2DbService');

/**
 * POST /api/v2/agent/analyze
 * Runs the AI Sustainability Agent against an existing saved scan (`analysisId`)
 * or direct structured scan metrics (`scanData`).
 */
router.post('/analyze', authenticateToken, async (req, res) => {
    try {
        const userId = req.user.id;
        const { analysisId, scanData, forceRefresh = false } = req.body || {};

        let inputPayload = null;
        let resolvedAnalysisId = null;

        if (analysisId != null) {
            const parsedId = Number(analysisId);
            if (!Number.isInteger(parsedId) || parsedId <= 0) {
                return res.status(400).json({ error: 'analysisId must be a positive integer.' });
            }

            if (!forceRefresh) {
                try {
                    const cached = await getLatestAgentReportForAnalysis(userId, parsedId);
                    // Only reuse cached report if it came from Gemini, OR if no AI_API_KEY is available.
                    // Never let an old fallback report permanently block a live Gemini attempt when AI_API_KEY is configured.
                    const shouldServeCache =
                        cached &&
                        (cached.generationMode === 'gemini' || !process.env.AI_API_KEY);
                    if (shouldServeCache) {
                        return res.json({
                            status: 'OK',
                            cached: true,
                            report: {
                                ...cached,
                                provenance:
                                    cached.generationMode === 'gemini'
                                        ? 'AI-GENERATED'
                                        : 'RULE-BASED',
                                disclaimer:
                                    cached.generationMode === 'gemini'
                                        ? 'AI-GENERATED recommendations grounded in MEASURED scan telemetry. Advisory only — does not modify any website. Energy and CO2 figures are CALCULATED estimates.'
                                        : 'RULE-BASED deterministic fallback analysis (NOT generated by Gemini). Advisory only — does not modify any website. Energy and CO2 figures are CALCULATED estimates.',
                            },
                        });
                    }
                } catch (cacheErr) {
                    console.warn('[v2Agent] Cache lookup skipped:', cacheErr.message);
                }
            }

            const row = await getRawAnalysisRow(userId, parsedId);
            if (!row) {
                return res.status(404).json({ error: 'Baseline analysis record not found for this user.' });
            }

            inputPayload = { ...row, analysisId: parsedId };
            resolvedAnalysisId = parsedId;
        } else if (scanData && typeof scanData === 'object') {
            inputPayload = scanData;
        } else {
            return res.status(400).json({
                error: 'Provide either analysisId (existing scan) or scanData (structured scan metrics).',
            });
        }

        const report = await runSustainabilityAgent(inputPayload);

        let reportId = null;
        try {
            reportId = await saveAgentReport(userId, {
                ...report,
                analysisId: resolvedAnalysisId,
            });
        } catch (dbErr) {
            console.error('[v2Agent] Failed to persist agent report:', dbErr.message);
        }

        return res.status(200).json({
            status: 'OK',
            cached: false,
            report: {
                id: reportId,
                ...report,
            },
        });
    } catch (error) {
        console.error('[v2Agent] /analyze error:', error);
        const status = String(error?.message || '').startsWith('MISSING_SCAN_TELEMETRY') ? 400 : 500;
        return res.status(status).json({
            error: error?.message || 'AI Sustainability Agent failed to process request.',
        });
    }
});

/**
 * GET /api/v2/agent/reports
 * Lists saved AI Sustainability Agent reports for the authenticated user.
 */
router.get('/reports', authenticateToken, async (req, res) => {
    try {
        const reports = await getAgentReportsByUser(req.user.id, req.query.limit);
        return res.json({ reports });
    } catch (error) {
        console.error('[v2Agent] GET /reports error:', error);
        return res.status(500).json({ error: 'Failed to load AI Sustainability Agent reports.' });
    }
});

/**
 * GET /api/v2/agent/reports/:analysisId
 * Retrieves the latest AI Sustainability Agent report for a specific analysis ID.
 */
router.get('/reports/:analysisId', authenticateToken, async (req, res) => {
    try {
        const parsedId = Number(req.params.analysisId);
        if (!Number.isInteger(parsedId) || parsedId <= 0) {
            return res.status(400).json({ error: 'Invalid analysisId.' });
        }
        const report = await getLatestAgentReportForAnalysis(req.user.id, parsedId);
        if (!report) {
            return res.status(404).json({ error: 'No AI Sustainability Agent report found for this analysis.' });
        }
        return res.json({ report });
    } catch (error) {
        console.error('[v2Agent] GET /reports/:analysisId error:', error);
        return res.status(500).json({ error: 'Failed to load AI Sustainability Agent report.' });
    }
});

module.exports = router;
